#!/usr/bin/env python3
"""gen/modules_table.c: the lifted modules for the runtime loader (runtime/src/modules.c).
usage: gen_modules.py ref/lift/layout.json gen/modules_table.c"""
import json, os, re, sys

layout = json.load(open(sys.argv[1]))
out = ['/* generated by tools/gen_modules.py - do not edit */', '#include "w64_gen.h"', '']
rows = []
for relpath, base in layout.items():
    name = os.path.basename(relpath)
    sym = os.path.splitext(name)[0]
    gdir = os.path.join(os.path.dirname(sys.argv[2]), sym)
    n = len(re.findall(r'^\s*\{ 0x', open(os.path.join(gdir, 'recomp_imports.c')).read(), re.M))
    out += ['extern const recomp_entry_t %s_dispatch_table[];' % sym,
            'extern const uint32_t %s_dispatch_count;' % sym,
            'extern const hle_import_t %s_imports[];' % sym]
    rows.append('    { "%s", "%s", %sull, %s_dispatch_table, &%s_dispatch_count, %s_imports, %d },'
                % (name, relpath, base, sym, sym, sym, n))
out += ['', 'const w64_modspec_t w64_modspecs[] = {'] + rows + ['};',
        'const int w64_nmodspecs = %d;' % len(rows), '']
open(sys.argv[2], 'w').write('\n'.join(out))
print('modules', len(rows))
